/**
 * Main entry point.
 */
async function main(): Promise<void> {
  console.log('=== Encoding Codegen ===\n');

  // Ensure output directory exists
  mkdirSync(OUTPUT_DIR, { recursive: true });

  // Process each encoding
  for (const encoding of Object.keys(ENCODINGS) as EncodingName[]) {
    await processEncoding(encoding);
    console.log('');
  }

  // Generate derivative encodings
  generateP50kEdit();
  console.log('');

  generateO200kHarmony();
  console.log('');

  // Generate index
  generateIndex();

  console.log('\n=== Done ===');
}

main().catch((error) => {
  console.error('Error:', error);
  process.exit(1);
});
